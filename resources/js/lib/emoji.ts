const RECENT_KEY = 'gc.emoji.recent';
const RECENT_LIMIT = 32;

export function recentEmoji(): string[] {
    try {
        const value = JSON.parse(localStorage.getItem(RECENT_KEY) ?? '[]');

        return Array.isArray(value) ? value.slice(0, RECENT_LIMIT) : [];
    } catch {
        return [];
    }
}

export function rememberEmoji(emoji: string): string[] {
    const next = [emoji, ...recentEmoji().filter((e) => e !== emoji)].slice(
        0,
        RECENT_LIMIT,
    );
    try {
        localStorage.setItem(RECENT_KEY, JSON.stringify(next));
    } catch {
        // Приватний режим або переповнене сховище — недавні просто не збережуться.
    }

    return next;
}
