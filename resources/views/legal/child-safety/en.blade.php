<p>These standards apply to the <strong>{{ $legal['name'] }}</strong> social network — the website <a href="{{ $legal['site'] }}">{{ $legal['site'] }}</a> and the <strong>{{ $legal['name'] }}</strong> Android app on Google Play (developer: <strong>{{ $legal['developer'] }}</strong>). They are part of our <a href="/terms?lang=en">Terms of Use</a> and are binding for every user.</p>

<h2>1. Zero tolerance for child sexual abuse and exploitation</h2>
<p>{{ $legal['name'] }} <strong>strictly prohibits</strong> any child sexual abuse and exploitation (CSAE), including:</p>
<ul>
    <li>child sexual abuse material (CSAM) in any form — photos, videos, drawings, generated or altered images, text, or links to such material;</li>
    <li>grooming — building contact or trust with a child for the purpose of sexual abuse or exploitation, including in direct messages, chats, voice rooms and groups;</li>
    <li>inappropriate interaction targeted at a child (for example, groping or caressing, or describing or proposing it);</li>
    <li>sexualisation of minors: sexual comments, propositions, role-play or sexual conversations with or about minors;</li>
    <li>sextortion — demanding intimate images from a minor or blackmailing them with such images;</li>
    <li>child trafficking, or offering or seeking minors for sexual exploitation;</li>
    <li>sharing, requesting, trading, selling or storing any of the above, or helping others to do so.</li>
</ul>
<p>The prohibition applies across the whole service: posts, comments, photos and albums, stories and moments, profiles, private and group chats, voice rooms, communities, families, clans and servers.</p>

<h2>2. User age</h2>
<p>{{ $legal['name'] }} is intended for people aged 13 and over. Users under 14 need the consent of a parent or legal guardian. Accounts of people below the minimum age are removed.</p>

<p>{{ $legal['name'] }} also prohibits showing adult content to children and posting content that encourages behaviour dangerous to children.</p>

<h2>3. How we prevent abuse</h2>
<ul>
    <li>Content moderation: {{ $legal['name'] }} moderators review reports and images flagged by automated filters.</li>
    <li>Automated image checks at upload: suspicious files are flagged for moderators.</li>
    <li>Contact controls: users can make their profile private, limit who can message them, and block anyone.</li>
    <li>Reports marked “Child safety” are handled first — they always stay at the top of the moderation queue.</li>
</ul>

<h2>4. How to report</h2>
<p>If you see content or behaviour that puts a child at risk, tell us right away:</p>
<ul>
    <li><strong>In the app and on the website:</strong> on a person’s profile or in a message menu choose “Report” → “Child safety / sexual exploitation”.</li>
    <li><strong>By e-mail:</strong> <a href="mailto:{{ $legal['email'] }}?subject=Child%20safety">{{ $legal['email'] }}</a> with the subject “Child safety”. Include a link to the profile, post or chat (do not forward the illegal material itself).</li>
</ul>
<p>If a child is in immediate danger, contact your local police right away (in Ukraine — 102).</p>

<h2>5. What we do after a report</h2>
<ul>
    <li>We immediately remove CSAE material and block access to it.</li>
    <li>We permanently ban offending accounts.</li>
    <li>We preserve data needed for investigations, as permitted by law.</li>
    <li>We report child sexual abuse material to the competent authorities — the National Police of Ukraine (Cyber Police), <a href="https://report.cybertip.org/" target="_blank" rel="noopener">NCMEC</a> and other authorised organisations, as required by applicable law.</li>
    <li>We cooperate with law enforcement on lawful requests.</li>
</ul>

<h2>6. Legal compliance</h2>
<p>{{ $legal['name'] }} complies with the child-protection laws of Ukraine, applicable international law and Google Play’s Child Safety Standards policy.</p>

