<h2>1. Нульова толерантність до сексуального насильства над дітьми та їх експлуатації</h2>
<p>У {{ $legal['name'] }} <strong>суворо заборонено</strong> будь-яке сексуальне насильство над дітьми та їх сексуальну експлуатацію (CSAE), зокрема:</p>
<ul>
    <li>матеріали сексуального насильства над дітьми (CSAM) у будь-якій формі — фото, відео, малюнки, згенеровані чи змінені зображення, тексти, посилання на такі матеріали;</li>
    <li>грумінг — встановлення контакту з дитиною чи довіри з нею з метою сексуального насильства чи експлуатації, зокрема в особистих повідомленнях, чатах, голосових кімнатах і групах;</li>
    <li>сексуалізацію неповнолітніх: сексуальні коментарі, пропозиції, рольові ігри чи спілкування сексуального характеру з неповнолітніми або про них;</li>
    <li>сексторшн — вимагання інтимних зображень від неповнолітнього чи шантаж ними;</li>
    <li>торгівлю дітьми, пропозиції чи пошук неповнолітніх з метою сексуальної експлуатації;</li>
    <li>поширення, запит, обмін, продаж чи зберігання будь-чого з переліченого, а також допомогу в цьому.</li>
</ul>
<p>Заборона діє в усіх частинах сервісу: публікаціях, коментарях, фото й альбомах, історіях і моментах, профілях, особистих і групових чатах, голосових кімнатах, спільнотах, сім’ях, кланах і на серверах.</p>

