<h2>1. 付款方式</h2>
<ul>
    <li><strong>个人账户。</strong>付费产品使用您的账户余额购买（GameCon+ → 账户）。您可通过充值页面列出的第三方打赏与支付服务（例如 Donatello、Diaka、Donatik、Buy Me a Coffee 或 Patreon）充值，并注明页面显示的充值代码。</li>
    <li><strong>到账。</strong>服务支持时，充值会在几分钟内自动到账；否则经人工核对后到账，通常在 24 小时内。如付款未附代码或金额不同，我们在确认属于您后按实际收到的金额入账。</li>
    <li><strong>不涉及银行卡信息。</strong>各服务按其自身条款处理付款。我们从不接收或存储您的银行卡信息。</li>
    <li><strong>Android 应用。</strong>在我们的 Android 应用中购买通过 Google Play 结算进行，其取消与退款适用 Google Play 的政策。</li>
</ul>

<h2>2. 即时开通</h2>
<p>使用余额购买后<strong>立即</strong>生效，可在网站和应用中使用。礼物即时到达接收者账号；服务器推广立即开始，若付费名额已满，则从付款前显示的首个空闲时间开始。新的 GameCon+ 期限在当前期限结束后开始，已付费天数不会损失。</p>

<h2>3. 自动续订与取消</h2>
<ul>
    <li><strong>自愿开启。</strong>仅当您在购买 GameCon+ 或家庭方案时选择，才会开启自动续订。</li>
    <li><strong>仅从余额扣款。</strong>在付费期限结束前约 24 小时，从账户余额扣除价格 —— 绝不从银行卡扣款。余额不足时我们会通知您，并在您充值后立即续订。</li>
    <li><strong>一键取消。</strong>您可随时在 GameCon+ → 账户 中关闭自动续订。无取消费、违约金或最低期限，访问权限保留至付费期限结束。</li>
</ul>

<h2>4. 退款</h2>
<h3>4.1. 未使用的充值 —— 14 天</h3>
<p>在<strong>充值后 14 天内</strong>，您可申请退还该笔充值中未使用的部分。我们按实际收到的金额，通过原服务（如支持退款）或银行转账至您本人名下账户退还。超过 14 天后，未使用余额仍可用于购买，但不予退还，法律另有规定的除外。</p>
<h3>4.2. 购买 —— 14 天</h3>
<p>在<strong>购买后 14 天内</strong>（包括礼物或服务器推广），您可申请取消；价格将退回账户余额，相应权益终止。如该款项来自最近 14 天内的充值，您还可依第 4.1 条申请退回现金。这是参照欧盟、英国和美国消费者标准自愿提供的退款期；购买即表示您要求立即提供数字服务，并在法律要求时确认服务完全提供后法定撤回权可能终止。</p>
<h3>4.3. 自动续订</h3>
<p>如您忘记关闭自动续订且续订后未使用付费功能，请在 14 天内联系我们，我们会将续订价格退回您的余额。</p>
<h3>4.4. 技术故障与重复扣款</h3>
<ul>
    <li>如同一产品或期限被重复扣款，或充值进入错误账户，我们将全额纠正，不受上述期限限制。</li>
    <li>如因我方故障导致付费功能无法使用且未能在合理时间内修复，我们将全额或按比例退还受影响期限的费用。</li>
</ul>
