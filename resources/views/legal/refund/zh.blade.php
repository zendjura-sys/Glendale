<p>新订阅、礼物或推广可在<strong>首次付款后 14 天内</strong>申请全额退款，符合欧盟、英国和美国的消费者标准。购买即表示您要求立即提供数字服务；在法律要求时，您确认服务完全提供后可能丧失法定撤回权——但我们仍自愿遵守此处的 14 天退款期，第 4.4 条另有规定的除外。</p>
<h3>4.2. 续订</h3>
<p>自动续订的款项一般不予退还，因为您可随时在续订前取消。如您忘记取消且续订后未使用付费功能，请在 14 天内联系我们，我们将考虑退款。</p>
