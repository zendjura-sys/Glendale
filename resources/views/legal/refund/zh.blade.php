<ul>
    <li>如同一产品或周期被重复扣款，或在确认取消后仍被扣款，我们将全额退还多扣或错误的金额，不受上述期限限制。</li>
    <li>如因我方原因付费功能无法使用且未能在合理时间内修复，我们将全额或按比例退还受影响周期的费用。</li>
