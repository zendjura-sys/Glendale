<p>Esta política explica cómo funcionan las cancelaciones y reembolsos de los productos de pago de {{ $legal['name'] }} (GameCon+, plan familiar, regalos GameCon+ y promoción de servidores).</p>

<h2>1. Merchant of Record — Paddle</h2>
<p>Nuestro proceso de pedido lo gestiona nuestro revendedor en línea <strong>Paddle.com</strong>. <strong>Paddle.com es el Merchant of Record</strong> de todos los pedidos: procesa los pagos, aplica impuestos, emite recibos y facturas, y gestiona reembolsos y consultas de pago. Los reembolsos se devuelven al método de pago original.</p>

<h2>2. Suscripción digital con acceso inmediato</h2>
<p>GameCon+ es una suscripción digital de software como servicio (SaaS). Las funciones se activan <strong>de inmediato</strong> tras el pago (normalmente en segundos). Los regalos se acreditan al instante; la promoción del servidor empieza al momento o, si todos los espacios están ocupados, en la fecha indicada antes del pago.</p>

<h2>3. Cancelación</h2>
<ul>
    <li><strong>Un clic.</strong> Puedes cancelar en cualquier momento en la página GameCon+ de tu perfil (botón “Cancelar”), con el enlace del recibo de Paddle o escribiéndonos.</li>
    <li><strong>Sin cargos ocultos.</strong> Sin penalizaciones, comisiones de cancelación ni permanencia mínima.</li>
    <li><strong>Acceso hasta el final del periodo.</strong> Tras cancelar, la suscripción no se renueva; GameCon+ sigue activo hasta el final del periodo pagado y puedes reactivarla con un clic.</li>
    <li>Eliminar la cuenta cancela las suscripciones activas.</li>
</ul>

<h2>4. Reembolsos</h2>
<h3>4.1. 14 días para el reembolso</h3>
<p>Puedes solicitar el reembolso completo dentro de los <strong>14 días siguientes al primer pago</strong> de una nueva suscripción, un regalo o una promoción, conforme al estándar de consumo de la UE, el Reino Unido y EE. UU. Al comprar solicitas acceso inmediato al servicio digital; cuando la ley lo exija, reconoces que puedes perder el derecho de desistimiento una vez prestado el servicio — aun así respetamos voluntariamente el plazo de 14 días aquí descrito, sin perjuicio del apartado 4.4.</p>
<h3>4.2. Renovaciones</h3>
<p>Los pagos de renovación automática en general no son reembolsables, ya que puedes cancelar antes. Si olvidaste cancelar y no has usado las funciones desde la renovación, escríbenos en un plazo de 14 días y estudiaremos el reembolso.</p>
<h3>4.3. Fallos técnicos y cargos duplicados</h3>
<ul>
    <li>Si se te cobró dos veces el mismo producto o periodo, o tras una cancelación confirmada, reembolsaremos íntegramente el importe erróneo, con independencia de los plazos anteriores.</li>
    <li>Si las funciones de pago no funcionaron por causa nuestra y no lo solucionamos en un plazo razonable, reembolsaremos el periodo afectado total o proporcionalmente.</li>
</ul>
<h3>4.4. Límites y abuso</h3>
<ul>
    <li>Podemos denegar un reembolso en caso de abuso, p. ej. ciclos repetidos de compra y reembolso, solicitudes tras un uso sustancial de un regalo o promoción, uso del plazo para obtener las funciones gratis, fraude o contracargos con una solicitud abierta.</li>
    <li>No procede reembolso si la cuenta fue suspendida o eliminada por una infracción grave de los <a href="{{ $legal['site'] }}/terms">Términos del servicio</a>, salvo que la ley disponga otra cosa.</li>
    <li>Los cambios en la lista de funciones de pago (Términos, sección 7) no dan por sí solos derecho a reembolso, salvo lo exigido por la normativa de consumo.</li>
</ul>
<p>Esta política no limita tus derechos imperativos como consumidor.</p>

