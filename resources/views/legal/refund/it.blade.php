    <li>L’eliminazione dell’account annulla gli abbonamenti attivi.</li>
</ul>

<h2>4. Rimborsi</h2>
<h3>4.1. 14 giorni per il rimborso</h3>
<p>Puoi chiedere il rimborso completo entro <strong>14 giorni dal primo pagamento</strong> di un nuovo abbonamento, di un regalo o di una promozione, secondo lo standard dei consumatori di UE, Regno Unito e USA. Acquistando chiedi l’accesso immediato al servizio digitale; ove previsto dalla legge riconosci che il diritto di recesso può venir meno una volta eseguito il servizio — tuttavia rispettiamo volontariamente la finestra di 14 giorni descritta, salvo quanto previsto al punto 4.4.</p>
<h3>4.2. Rinnovi</h3>
<p>I pagamenti di rinnovo automatico in genere non sono rimborsabili, perché puoi disdire prima. Se hai dimenticato di disdire e non hai usato le funzioni dopo il rinnovo, scrivici entro 14 giorni e valuteremo il rimborso.</p>
<h3>4.3. Problemi tecnici e doppi addebiti</h3>
<ul>
    <li>In caso di doppio addebito per lo stesso prodotto o periodo, o di addebito dopo una disdetta confermata, rimborsiamo integralmente l’importo errato, indipendentemente dai termini sopra.</li>
    <li>Se le funzioni a pagamento non hanno funzionato per causa nostra e non abbiamo risolto in tempi ragionevoli, rimborsiamo il periodo interessato in tutto o in proporzione.</li>
</ul>
