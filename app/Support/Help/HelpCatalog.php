/**
 * Довідка GameCon (/help): розділи → статті. Єдине джерело текстів — цей клас.
 *
 * Тексти — українські рядки-ключі: їх збирає scripts/i18n/extract-php.php у каталог перекладів,
 * а Translations::tree перекладає пропси Inertia мовою інтерфейсу (ключі блоків — не «body»,
 * бо «body» вважається текстом користувача і не перекладається).
 *
 * Блоки статті: p — абзац, h — підзаголовок, steps — кроки, list — список, tip — порада,
 * note — застереження. У тексті можна посилатися на сторінку сайту: [підпис](/шлях).
 * Розділ із module показується, лише коли модуль увімкнено (вимкнений розділ сайту — 404 і тут).
 *
 * @phpstan-type Block array{type: string, text?: string, items?: list<string>}
 * @phpstan-type Article array{slug: string, title: string, summary: string, blocks: list<Block>, related: list<string>}
 * @phpstan-type Category array{slug: string, title: string, summary: string, icon: string, module: string|null, articles: list<Article>}
 */
class HelpCatalog
