    /** Дата останнього перегляду текстів (показується під статтею). */
    public const UPDATED = '2026-10-23';

    public function __construct(private readonly ModuleManager $modules) {}

    /**
     * Розділи, доступні на сайті (з урахуванням вимкнених модулів).
     *
     * @return list<Category>
     */
    public function categories(): array
    {
        return array_values(array_filter(
            self::all(),
            fn (array $category) => $category['module'] === null || $this->modules->enabled($category['module']),
        ));
    }

    /** @return Category|null */
    public function category(string $slug): ?array
    {
        foreach ($this->categories() as $category) {
            if ($category['slug'] === $slug) {
                return $category;
            }
        }

        return null;
    }

    /** @return array{0: Category, 1: Article}|null */
    public function article(string $category, string $slug): ?array
    {
        $found = $this->category($category);
        foreach ($found['articles'] ?? [] as $article) {
            if ($article['slug'] === $slug) {
                return [$found, $article];
            }
        }

        return null;
    }

    /**
     * Пов’язані статті з посилань «розділ/стаття» (недоступні пропускаються).
     *
     * @param  list<string>  $keys
     * @return list<array{category: string, slug: string, title: string, summary: string}>
     */
    public function related(array $keys): array
    {
        $out = [];
        foreach ($keys as $key) {
            [$category, $slug] = array_pad(explode('/', $key, 2), 2, '');
            $found = $this->article($category, $slug);
            if ($found !== null) {
                $out[] = ['category' => $category, 'slug' => $slug, 'title' => $found[1]['title'], 'summary' => $found[1]['summary']];
            }
        }

        return $out;
    }

    /** @return Block */
    private static function p(string $text): array
    {
        return ['type' => 'p', 'text' => $text];
    }

    /** @return Block */
    private static function h(string $text): array
    {
        return ['type' => 'h', 'text' => $text];
    }

    /** @return Block */
    private static function tip(string $text): array
    {
        return ['type' => 'tip', 'text' => $text];
    }

    /** @return Block */
    private static function note(string $text): array
    {
        return ['type' => 'note', 'text' => $text];
    }

    /**
     * @param  list<string>  $items
     * @return Block
     */
    private static function steps(array $items): array
    {
        return ['type' => 'steps', 'items' => $items];
    }

    /**
     * @param  list<string>  $items
     * @return Block
     */
    private static function list(array $items): array
    {
        return ['type' => 'list', 'items' => $items];
    }

    /**
     * @param  list<Block>  $blocks
     * @param  list<string>  $related
     * @return Article
     */
    private static function article_(string $slug, string $title, string $summary, array $blocks, array $related = []): array
    {
        return ['slug' => $slug, 'title' => $title, 'summary' => $summary, 'blocks' => $blocks, 'related' => $related];
    }

    /**
     * @param  list<Article>  $articles
     * @return Category
     */
    private static function category_(string $slug, string $title, string $summary, string $icon, ?string $module, array $articles): array
    {
        return ['slug' => $slug, 'title' => $title, 'summary' => $summary, 'icon' => $icon, 'module' => $module, 'articles' => $articles];
    }

